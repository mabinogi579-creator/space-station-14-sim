using System.Numerics;
using Content.Client.UserInterface.Systems.Chat.Widgets;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Screens;

[GenerateTypedNameReferences]
public sealed partial class DefaultGameScreen : InGameScreen
{
    public DefaultGameScreen()
    {
        RobustXamlLoader.Load(this);

        AutoscaleMaxResolution = new Vector2i(1080, 770);

        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorPreset(ViewportContainer, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(TopLeft, LayoutPreset.TopLeft, margin: 10);
        SetAnchorAndMarginPreset(Ghost, LayoutPreset.BottomWide, margin: 80);
        SetAnchorAndMarginPreset(Inventory, LayoutPreset.BottomLeft, margin: 5);
        SetAnchorAndMarginPreset(Hotbar, LayoutPreset.BottomWide, margin: 5);
        // Colony: the chat box lives in the bottom right corner, with a button that collapses it.
        // (It no longer resizes or remembers a size; that code assumed the top right corner.)
        Chat.Resizable = false;
        SetAnchorAndMarginPreset(Chat, LayoutPreset.BottomRight, margin: 10);
        SetGrowHorizontal(Chat, GrowDirection.Begin);
        SetGrowVertical(Chat, GrowDirection.Begin);
        SetMarginBottom(Chat, -48);
        Chat.MinSize = new Vector2(480, 280);

        var chatToggle = new Button { Text = "Chat", ToggleMode = true, Pressed = true, MinSize = new Vector2(80, 30) };
        chatToggle.OnToggled += args => Chat.Visible = args.Pressed;
        AddChild(chatToggle);
        SetAnchorAndMarginPreset(chatToggle, LayoutPreset.BottomRight, margin: 10);
        SetGrowHorizontal(chatToggle, GrowDirection.Begin);
        SetGrowVertical(chatToggle, GrowDirection.Begin);
        SetAnchorAndMarginPreset(Alerts, LayoutPreset.TopRight, margin: 10);

        Chat.OnChatResizeFinish += ChatOnResizeFinish;

        MainViewport.OnResized += ResizeActionContainer;
        Inventory.OnResized += ResizeActionContainer;
    }

    private void ResizeActionContainer()
    {
        float indent = Inventory.Size.Y + TopBar.Size.Y + 40;
        Actions.ActionsContainer.MaxGridHeight = MainViewport.Size.Y - indent;
    }

    private void ChatOnResizeFinish(Vector2 _)
    {
        var marginBottom = Chat.GetValue<float>(MarginBottomProperty);
        var marginLeft = Chat.GetValue<float>(MarginLeftProperty);
        OnChatResized?.Invoke(new Vector2(marginBottom, marginLeft));
    }

    private void ChatOnResized()
    {
        var marginBottom = Chat.GetValue<float>(MarginBottomProperty);
        SetMarginTop(Alerts, marginBottom);
    }

    public override ChatBox ChatBox => Chat;

    //TODO: There's probably a better way to do this... but this is also the easiest way.
    public override void SetChatSize(Vector2 size)
    {
        // Colony: the chat box has a fixed place in the bottom right, so saved sizes are ignored.
    }
}
